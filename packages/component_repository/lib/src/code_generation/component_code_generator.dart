import 'package:component_repository/component_repository.dart';
import 'package:component_repository/src/code_generation/dart_names.dart';
import 'package:dart_style/dart_style.dart';
import 'package:pub_semver/pub_semver.dart';

/// {@template component_code_generator}
/// Generates the Dart source of a [Component] and its children.
///
/// The root becomes a public class, named after the component with the
/// `$` prefix of generated code (`player` becomes `$Player`), that extends
/// the Flame class of its type, so games can subclass it
/// (`class Player extends $Player`). Every child is exposed through a
/// getter, named after the child, on the component it is inside. Children
/// that have children of their own get a generated class too, so their
/// children have getters as well; the others are plain Flame components.
///
/// Every component type has a case in [generate], and every property is
/// written the same way `flame_mapping.dart` applies it to the preview.
/// {@endtemplate}
class ComponentCodeGenerator {
  /// {@macro component_code_generator}
  const new();

  /// The first line of every generated file.
  static const header = '// GENERATED CODE - DO NOT MODIFY BY HAND.';

  static final _formatter = DartFormatter(languageVersion: Version(3, 8, 0));

  /// The extension of every generated file.
  static const fileExtension = '.generated.dart';

  /// The name of the file generated for [component], such as
  /// `player_ship.generated.dart`.
  String fileName(Component component) {
    return '${dartFileName(component.name)}$fileExtension';
  }

  /// Returns the formatted Dart source of [component].
  String generate(Component component) {
    final rootClass = dartRootClassName(component.name);
    final buffer = StringBuffer()
      ..writeln(header)
      ..writeln('// Generated by Flame Component Editor.')
      ..writeln()
      ..writeln('// coverage:ignore-file')
      ..writeln('// ignore_for_file: type=lint')
      ..writeln();
    // `dart:ui` is only needed for paints; an unused import is a warning.
    if (component.nodes.any((node) => node is PaintedComponent)) {
      buffer
        ..writeln("import 'dart:ui';")
        ..writeln();
    }
    buffer
      ..writeln("import 'package:flame/components.dart';")
      ..writeln();

    _writeClass(
      buffer,
      component,
      rootName: component.name,
      className: rootClass,
      doc: 'The `${component.name}` component.',
      parameters: '{super.position, super.angle, super.anchor, super.priority}',
      arguments: _arguments(component, withPosition: false),
    );
    for (final node in component.nodes.skip(1)) {
      if (node.children.isEmpty) continue;
      _writeClass(
        buffer,
        node,
        rootName: component.name,
        className: dartChildClassName(component.name, node.name),
        doc: 'The `${node.name}` child component of [$rootClass].',
        parameters: '',
        arguments: _arguments(node, withPosition: true),
      );
    }
    return _formatter.format(buffer.toString());
  }

  void _writeClass(
    StringBuffer buffer,
    Component component, {
    required String rootName,
    required String className,
    required String doc,
    required String parameters,
    required List<String> arguments,
  }) {
    final children = component.children;
    buffer
      ..writeln('/// $doc')
      ..writeln('class $className extends ${_flameClass(component)} {')
      ..writeln('  /// Creates a [$className].')
      ..write('  $className($parameters)')
      ..write(' : super(${_list(arguments)})');

    if (children.isEmpty) {
      buffer.writeln(';');
    } else {
      final getters = children.map((child) => dartMemberName(child.name));
      buffer.writeln(
        children.length == 1
            ? ' { add(${getters.single}); }'
            : ' { addAll([${_list(getters)}]); }',
      );
    }

    for (final child in children) {
      final type = child.children.isEmpty
          ? _flameClass(child)
          : dartChildClassName(rootName, child.name);
      final value = child.children.isEmpty
          ? '$type(${_list(_arguments(child, withPosition: true))})'
          : '$type()';
      buffer
        ..writeln()
        ..writeln('  /// The `${child.name}` child component.')
        ..writeln('  final $type ${dartMemberName(child.name)} = $value;');
    }
    buffer
      ..writeln('}')
      ..writeln();
  }

  static String _flameClass(Component component) {
    return switch (component) {
      RectangleComponent() => 'RectangleComponent',
      PositionComponent() => 'PositionComponent',
      CircleComponent() => 'CircleComponent',
    };
  }

  /// The arguments of the Flame constructor, one per property. The root
  /// position, angle and anchor are left to whoever uses the component.
  static List<String> _arguments(
    Component component, {
    required bool withPosition,
  }) {
    return [
      if (component case final PositionedComponent c when withPosition)
        'position: ${_vector(c.position.x, c.position.y)}',
      // Flame already defaults to no rotation and the top left anchor.
      if (component case final RotatedComponent c
          when withPosition && c.angle != ComponentAngle.zero)
        'angle: ${_number(c.angle.radians)}',
      if (component case final AnchoredComponent c
          when withPosition && c.anchor != ComponentAnchor.topLeft)
        'anchor: ${_anchor(c.anchor)}',
      if (component case final SizedComponent c)
        'size: ${_vector(c.size.width, c.size.height)}',
      if (component case final RadiusComponent c)
        'radius: ${_number(c.radius.radius)}',
      if (component case final PaintedComponent c) 'paint: ${_paint(c.paint)}',
    ];
  }

  /// Joins [items] with trailing commas, so the formatter splits them one
  /// per line when they don't fit.
  static String _list(Iterable<String> items) {
    return items.map((item) => '$item,').join();
  }

  static String _vector(double x, double y) {
    return 'Vector2(${_number(x)}, ${_number(y)})';
  }

  static String _number(double value) {
    return value == value.truncateToDouble()
        ? value.toInt().toString()
        : value.toString();
  }

  static String _anchor(ComponentAnchor anchor) {
    final name = anchor.presetName;
    return name != null
        ? 'Anchor.$name'
        : 'Anchor(${_number(anchor.x)}, ${_number(anchor.y)})';
  }

  static String _paint(ComponentPaint paint) {
    final color = paint.color.toRadixString(16).toUpperCase().padLeft(8, '0');
    return [
      'Paint()',
      '..color = const Color(0x$color)',
      if (paint.style == PaintStyle.stroke) '..style = PaintingStyle.stroke',
    ].join();
  }
}
